import {
  describeProvenance,
  isSimulated,
  stalenessOf,
  type Sourced,
} from '@/lib/provenance';

interface SourcedFigureProps {
  figure: Sourced<number | string>;
  label: string;
  sub?: string;
  size?: 'sm' | 'md' | 'lg';
  format?: (v: number | string) => string;
}

const SIZES = {
  sm: 'text-xl',
  md: 'text-3xl',
  lg: 'text-5xl',
} as const;

export function SourcedFigure({
  figure,
  label,
  sub,
  size = 'md',
  format,
}: SourcedFigureProps) {
  const simulated = isSimulated(figure.provenance);
  const stale = stalenessOf(figure.provenance);
  const shown =
    format?.(figure.value) ??
    (typeof figure.value === 'number' ? figure.value.toLocaleString('en-NG') : figure.value);

  return (
    <div className="flex flex-col gap-1">
      <div className="flex items-center gap-2">
        <span className="text-[11px] font-medium uppercase tracking-[0.14em] text-ink-faint">
          {label}
        </span>
        {simulated && <SimulatedTag />}
        {stale && <StaleTag reason={stale} />}
      </div>

      <span
        className={`figure ${SIZES[size]} font-semibold text-ink`}
        title={describeProvenance(figure.provenance)}
      >
        {shown}
      </span>

      {sub && <span className="text-xs text-ink-muted">{sub}</span>}

      <span className="mt-0.5 text-[10px] leading-tight text-ink-faint">
        {describeProvenance(figure.provenance)}
      </span>
    </div>
  );
}

export function SimulatedTag() {
  return (
    <span
      className="rounded-sm border border-passive/40 bg-passive/10 px-1.5 py-px text-[9px] font-semibold uppercase tracking-[0.12em] text-passive"
      title="Generated by the scenario engine. Not real data and never published."
    >
      Simulated
    </span>
  );
}

export function StaleTag({ reason }: { reason: string }) {
  return (
    <span
      className="rounded-sm border border-line-bright bg-surface-raised px-1.5 py-px text-[9px] font-semibold uppercase tracking-[0.12em] text-ink-muted"
      title={reason}
    >
      Stale source
    </span>
  );
}
